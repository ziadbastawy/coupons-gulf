/** Keep Latin codes readable inside Arabic sentences. */
export const iso = (v: string) => `\u2068${v}\u2069`

export type Dict = (typeof dict)['ar']
export const t = (lang: Lang): Dict => dict[lang] as Dict

export function formatDate(iso: string | null | undefined, lang: Lang) {
  if (!iso) return ''
  return new Intl.DateTimeFormat(lang === 'ar' ? 'ar' : 'en-GB', {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
    calendar: 'gregory',
    numberingSystem: 'latn',
    timeZone: 'Asia/Riyadh',
  }).format(new Date(iso))
}
